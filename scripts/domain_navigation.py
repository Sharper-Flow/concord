from functools import lru_cache
import hashlib
import json
from pathlib import Path
import re
import subprocess

import knowledge_index

COMPANION = ".concord/domain-navigation.v1.json"
REGISTRY = ".concord/docs/knowledge/domain-registry.json"
TOOLING = ".concord/tooling.v1.json"
AGENT_SURFACE = "contracts/agent-tool-surface.v1.json"
OUTPUT = ".concord/navigation"
GENERATED = "DO NOT EDIT: generated by scripts/generate-domain-navigation.py"
SCHEMA_1_0 = ("schema_version", "rules", "unresolved", "test_coverage")
SCHEMA_1_1 = (*SCHEMA_1_0, "mechanisms", "catalog_bindings", "dependency_interpretations")
LAW_KINDS = ("constitution", "decision", "spec")
MECHANISM_FIELDS = ("owner_id", "domain_id", "responsibility", "source_paths", "contract_refs",
                    "law_refs", "control_law_ids", "check_ids")
BINDING_FIELDS = ("catalog", "entry_id", "owner_id")
INTERPRETATION_FIELDS = ("source_domain_id", "kind", "target_domain_id", "law_refs", "contract_refs")
CATALOGS = ("cli", "agent", "workflow")
RELATION_KINDS = ("depends_on", "shares_contract_with")
MECHANISM_OWNER = re.compile(r"^mechanism:[a-z0-9][a-z0-9-]{0,63}$")
HEADING = re.compile(r"^ {0,3}#{1,6}(?:[ \t]+(?P<text>\S.*?))?[ \t]*$")
SCENARIO = re.compile(r"^ {0,3}Scenario:[ \t]+(?P<text>\S.*)$")
