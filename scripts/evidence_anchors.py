#!/usr/bin/env python3
"""Shared typed-anchor machinery for evidence-binding validators.

The floor-readiness and law-coverage validators both judge whether a `satisfied`
record is proved rather than asserted. The proof layer is the same in both
planes: typed anchors must resolve, and the executable kinds must be invoked
by a required workflow. Without a single source of truth the two validators
would drift and a record that one validator accepted would be a finding to the
other — the same defect restated in two syntaxes (CD-0047 D3).

Document-contract citations reuse native Go declaration presence without
claiming the stronger coverage assertion verdict.

What an anchor is:
- `go_test`: a Go test identified as `<package>.<TestName>`; resolves when the
  test is declared in that package and its body, or a same-package helper it
  calls, reaches a testing failure call. `go test ./...` is a required CI step.
- `scenario`: a corpus scenario id; resolves when the id appears in a corpus
  file under `.concord/scenarios/` and nothing in `internal/` defers it. A deferred
  scenario is executed by nothing and accepting it as evidence would assert a
  rule that no test enforces.
- `validator`: a Python checker or harness identified by `scripts/<prefix>-<name>.py`;
  resolves when the script exists and either the required CI workflow invokes
  it directly, or `scripts/check-json.py` nests it. A checker that exists but
  is wired into nothing proves nothing, which is the failure mode this whole
  machinery exists to surface.
- `generated`: a symbol owned by a generated artifact, identified as
  `<path>#<symbol>`; resolves when the symbol appears in a file whose leading
  comment carries the generator marker. Hand-written files carry no such
  guarantee.

The validator anchor pattern widens here to `scripts/(check|test)-*.py` so the
release/install test scripts are legal anchors too. The CI-invocation proof is
unchanged in principle: the script must appear in a required workflow file
(`.github/workflows/ci.yml`, `.github/workflows/release.yml`, or
`.github/workflows/pr-linear-link.yml`) or be nested via
`scripts/check-json.py`.
"""
from __future__ import annotations

import ast
import json
import os
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from coverage_state import bounded_text  # noqa: E402

ANCHOR_KINDS = ("go_test", "scenario", "validator", "generated", "adapter_test")

GO_TEST_ANCHOR = re.compile(r"^(?P<package>[a-z0-9/_]+)\.(?P<test>Test[A-Za-z0-9_]*)$")
VALIDATOR_ANCHOR = re.compile(r"^scripts/(check|test)-[a-z0-9-]+\.py$")
ADAPTER_TEST_ANCHOR = re.compile(r"^adapter/opencode/(?P<file>[A-Za-z0-9._-]+\.test\.ts)#(?P<test>.{3,256})$")
GENERATED_ANCHOR = re.compile(r"^(?P<file>[A-Za-z0-9./_-]+)#(?P<symbol>[A-Za-z_][A-Za-z0-9_]*)$")

GENERATED_MARKER = "Code generated by"

REQUIRED_WORKFLOWS = (
    ROOT / ".github/workflows/ci.yml",
    ROOT / ".github/workflows/release.yml",
    ROOT / ".github/workflows/pr-linear-link.yml",
)

GO_TEST_PROJECTOR = ROOT / "scripts/go-test-assertions/main.go"
_GO_TEST_SIGNATURE: tuple[str, tuple[tuple[str, int, int], ...], tuple[str, ...] | None] | None = None
_GO_TEST_FACTS: dict[str, dict[str, bool]] | GoTestProjectionError = {}


class GoTestProjectionError(RuntimeError):
    """The native projector supplied no valid test-declaration facts."""


def _go_test_source_signature(root: Path | None = None) -> tuple[tuple[str, int, int], ...]:
    """Source freshness is decided per call: every resolution rescans.

    The walk mirrors what an ``rglob("*.go")`` of ROOT observed: a name check
    against every entry kind (a directory named ``x.go`` counts), no descent
    into symlinked directories, ``stat`` following a leaf symlink, and an
    OSError from a directory scan or a stat dropping only that entry or
    subtree. ``.git`` and ``vendor`` components are pruned before descent,
    which yields the same signature as filtering them from the results while
    never scanning them; an excluded component in ROOT's own path empties the
    signature just as it filtered out every result before.
    """
    root = ROOT if root is None else root
    if ".git" in root.parts or "vendor" in root.parts:
        return ()
    files: list[tuple[str, int, int]] = []
    stack: list[tuple[str, str]] = [("", str(root))]
    while stack:
        prefix, directory = stack.pop()
        try:
            with os.scandir(directory) as entries:
                children = list(entries)
        except OSError:
            continue
        for entry in children:
            if entry.name == ".git" or entry.name == "vendor":
                continue
            relative = f"{prefix}/{entry.name}" if prefix else entry.name
            if entry.name.endswith(".go"):
                try:
                    stat = entry.stat()
                except OSError:
                    pass
                else:
                    files.append((relative, stat.st_mtime_ns, stat.st_size))
            try:
                if entry.is_dir(follow_symlinks=False):
                    stack.append((relative, f"{directory}/{entry.name}"))
            except OSError:
                pass
    return tuple(sorted(files))


def _load_go_test_facts(root: Path | None = None, candidates: set[str] | None = None) -> dict[str, dict[str, bool]]:
    global _GO_TEST_SIGNATURE, _GO_TEST_FACTS
    root = ROOT if root is None else root
    go_paths = tuple(sorted(name for name in candidates if name.endswith(".go"))) if candidates is not None else None
    signature = (str(root.resolve()), _go_test_source_signature(root), go_paths)
    if signature == _GO_TEST_SIGNATURE:
        if isinstance(_GO_TEST_FACTS, GoTestProjectionError):
            raise _GO_TEST_FACTS
        return _GO_TEST_FACTS
    try:
        command = ["go", "run", str(GO_TEST_PROJECTOR)]
        if go_paths is not None:
            command.append("-files-stdin")
        command.append(str(root))
        result = subprocess.run(
            command,
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
            timeout=120,
            input=json.dumps(go_paths) if go_paths is not None else None,
        )
        if result.returncode:
            raise GoTestProjectionError(
                f"Go test projector exited {result.returncode}: {result.stderr.strip()}"
            )
        document = json.loads(result.stdout)
        packages = document.get("packages") if isinstance(document, dict) else None
        if (
            not isinstance(document, dict)
            or document.get("schema_version") != "1.0"
            or not isinstance(packages, dict)
            or any(
                not isinstance(package, str)
                or not isinstance(tests, dict)
                or any(not isinstance(name, str) or not isinstance(asserts, bool) for name, asserts in tests.items())
                for package, tests in packages.items()
            )
        ):
            raise GoTestProjectionError("Go test projector returned an invalid declaration map")
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, subprocess.TimeoutExpired, GoTestProjectionError) as exc:
        error = exc if isinstance(exc, GoTestProjectionError) else GoTestProjectionError(f"Go test projector failed: {exc}")
        _GO_TEST_SIGNATURE, _GO_TEST_FACTS = signature, error
        if error is exc:
            raise
        raise error from exc
    _GO_TEST_FACTS = packages
    _GO_TEST_SIGNATURE = signature
    return _GO_TEST_FACTS


def go_test_exists(package: str, test: str, root: Path | None = None, candidates: set[str] | None = None) -> bool:
    """Citation presence is map membership, not the coverage assertion verdict."""
    return test in _load_go_test_facts(root, candidates).get(package, {})


def go_test_asserts(package: str, test: str) -> bool:
    """A Go test anchor resolves only when its AST fact says the test can fail.

    The projector parses every Go test file and admits one level of
    same-package helper delegation. A declaration without a failure-producing
    call is presence, not proof.
    """
    facts = _load_go_test_facts()
    package_facts = facts.get(package)
    return isinstance(package_facts, dict) and package_facts.get(test) is True


DEFERRAL = re.compile(r"""Deferrals\[\s*["'](?P<id>[^"']+)["']\s*\]\s*=""")


def deferred_scenarios() -> set[str]:
    """Scenario ids the corpus harnesses record as deferred rather than bound.

    A deferred scenario sits in the corpus and is executed by nothing. Accepting
    one as evidence would assert a rule that no test enforces — presence
    standing in for enforcement, which is the exact defect this machinery
    exists to surface. Reading the same registry the corpus test reads keeps
    the two answers from diverging.
    """
    found: set[str] = set()
    for path in (ROOT / "internal").rglob("*_test.go"):
        for match in DEFERRAL.finditer(path.read_text(encoding="utf-8", errors="replace")):
            found.add(match.group("id"))
    return found


def collect_ids(value: object) -> set[str]:
    found: set[str] = set()
    if isinstance(value, dict):
        for key, item in value.items():
            if key in {"id", "scenario_id", "scenario"} and isinstance(item, str):
                found.add(item)
            found |= collect_ids(item)
    elif isinstance(value, list):
        for item in value:
            found |= collect_ids(item)
    return found


def scenario_exists(scenario_id: str) -> bool:
    """A scenario anchor resolves when a corpus declares the id and nothing defers it."""
    if scenario_id in deferred_scenarios():
        return False
    directory = ROOT / ".concord/scenarios"
    if not directory.is_dir():
        return False
    for path in directory.rglob("*.json"):
        try:
            corpus = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            continue
        if scenario_id in collect_ids(corpus):
            return True
    return False


SCRIPT_REFERENCE = re.compile(r"^scripts/[a-z0-9-]+\.py$")
WORKFLOW_RUN_KEY = re.compile(r"^ {8}run:(?P<inline>.*)$")
WORKFLOW_RUN_BODY_INDENT = 10


def workflow_commands(text: str) -> str:
    """The shell text a workflow runs, without the prose that surrounds it.

    Matching a script name against the whole workflow file accepts a mention in
    a step name or a `#` comment as though it were an invocation. Only the
    `run:` blocks are commands. `scripts/check-script-tests.py` fails a workflow
    whose step keys carry the wrong indent, so the exact indents this reads are
    themselves enforced rather than assumed.
    """
    commands: list[str] = []
    in_body = False
    for line in text.splitlines():
        match = WORKFLOW_RUN_KEY.match(line)
        if match:
            commands.append(match.group("inline"))
            in_body = True
            continue
        if not in_body:
            continue
        if not line.strip():
            continue
        if line.startswith(" " * WORKFLOW_RUN_BODY_INDENT):
            commands.append(line)
            continue
        in_body = False
    return "\n".join(commands)


def _script_constant(node: ast.AST) -> str | None:
    for child in ast.walk(node):
        if isinstance(child, ast.Constant) and isinstance(child.value, str) and SCRIPT_REFERENCE.fullmatch(child.value):
            return child.value
    return None


def _is_subprocess_run(func: ast.AST) -> bool:
    return (
        isinstance(func, ast.Attribute)
        and func.attr == "run"
        and isinstance(func.value, ast.Name)
        and func.value.id == "subprocess"
    )


def nested_invocations(path: Path) -> set[str]:
    """Scripts a Python module reaches through `subprocess.run`.

    Derived from the call graph rather than from the file containing a string,
    because a mention is not a call. A script named in a comment, a docstring,
    or a variable that nothing runs must not count as proof that a law record
    is enforced.
    """
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, ValueError):
        return set()
    bindings: dict[str, str] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign):
            continue
        script = _script_constant(node.value)
        if script is None:
            continue
        for target in node.targets:
            if isinstance(target, ast.Name):
                bindings[target.id] = script
    invoked: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not _is_subprocess_run(node.func):
            continue
        for argument in node.args:
            for child in ast.walk(argument):
                if isinstance(child, ast.Constant) and isinstance(child.value, str):
                    if SCRIPT_REFERENCE.fullmatch(child.value):
                        invoked.add(child.value)
                elif isinstance(child, ast.Name) and child.id in bindings:
                    invoked.add(bindings[child.id])
    return invoked


def validator_runs_in_ci(script: str) -> bool:
    """A validator anchor resolves when a required workflow actually invokes it.

    A checker that exists but is not wired into the required workflow proves
    nothing, which is the failure mode this whole machinery exists to surface.
    Required workflows are `.github/workflows/ci.yml`,
    `.github/workflows/release.yml`, and `.github/workflows/pr-linear-link.yml`;
    each is a documented source of durable authority. `check-json.py` nests
    several sub-validators, so a nested invocation counts as invocation too.

    Both cases resolve structurally: a workflow proves invocation through its
    `run:` commands, and the nesting case through the `subprocess.run` call
    graph. Substring matching over whole files accepted a name in a comment as
    proof, which is presence standing in for enforcement.
    """
    if not (ROOT / script).is_file():
        return False
    for workflow in REQUIRED_WORKFLOWS:
        if workflow.is_file() and script in workflow_commands(workflow.read_text(encoding="utf-8")):
            return True
    return script in nested_invocations(ROOT / "scripts/check-json.py")


def adapter_test_exists(file: str, test: str) -> bool:
    """An adapter_test anchor resolves when the named bun:test registration
    exists in the named adapter suite file. The suite carries no third-party
    imports, so the file text is the closed source of truth for what it tests.
    """
    path = ROOT / "adapter/opencode" / file
    if not path.is_file():
        return False
    return f"test(\"{test}\"" in path.read_text(encoding="utf-8")


def adapter_suite_runs_in_ci() -> bool:
    """The adapter suite proves nothing unless a required workflow runs it.

    The same rule `validator_runs_in_ci` applies to Python validators: a suite
    that exists but is never invoked by CI is presence standing in for
    enforcement.
    """
    for workflow in REQUIRED_WORKFLOWS:
        if not workflow.is_file():
            continue
        if "bun test adapter/opencode" in workflow_commands(workflow.read_text(encoding="utf-8")):
            return True
    return False

def generated_symbol_exists(file: str, symbol: str) -> bool:
    """A generated anchor resolves when the symbol lives in a generated artifact.

    The artifact must carry the generator marker, because the guarantee being
    cited is that a generator owns the value — a hand-written file with the
    right symbol name carries no such guarantee.
    """
    candidate = PurePosixPath(file)
    if not file or candidate.is_absolute() or ".." in candidate.parts or candidate.as_posix() != file:
        return False
    try:
        real_root = ROOT.resolve(strict=True)
        target = (ROOT / file).resolve(strict=True)
    except (OSError, RuntimeError):
        return False
    if not target.is_relative_to(real_root) or not target.is_file():
        return False
    try:
        text = target.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    if GENERATED_MARKER not in text:
        return False
    return re.search(rf"\b{re.escape(symbol)}\b", text) is not None


def check_anchor(anchor: object, prefix: str, findings: list[str]) -> None:
    if not isinstance(anchor, dict):
        findings.append(f"{prefix}: anchor must be an object")
        return
    if set(anchor) != {"kind", "value"}:
        findings.append(f"{prefix}: anchor must carry exactly kind and value")
        return
    kind, value = anchor["kind"], anchor["value"]
    if kind not in ANCHOR_KINDS:
        findings.append(f"{prefix}: anchor kind must be one of {list(ANCHOR_KINDS)}, got {kind!r}")
        return
    if not bounded_text(value, 3, 512):
        findings.append(f"{prefix}: anchor value must be trimmed text of 3-512 characters")
        return

    if kind == "go_test":
        match = GO_TEST_ANCHOR.fullmatch(value)
        if not match:
            findings.append(f"{prefix}: go_test anchor must read <package>.<TestName>: {value!r}")
        else:
            try:
                resolved = go_test_asserts(match.group("package"), match.group("test"))
            except GoTestProjectionError as exc:
                findings.append(f"{prefix}: go_test projector failed: {exc}")
            else:
                if not resolved:
                    findings.append(f"{prefix}: go_test anchor does not resolve: {value!r}")
    elif kind == "scenario":
        if not scenario_exists(value):
            findings.append(f"{prefix}: scenario anchor is in no corpus under .concord/scenarios/: {value!r}")
    elif kind == "validator":
        if not VALIDATOR_ANCHOR.fullmatch(value):
            findings.append(
                f"{prefix}: validator anchor must read scripts/(check|test)-<name>.py: {value!r}"
            )
        elif not validator_runs_in_ci(value):
            findings.append(f"{prefix}: validator anchor is not invoked by a required workflow: {value!r}")
    elif kind == "adapter_test":
        match = ADAPTER_TEST_ANCHOR.fullmatch(value)
        if not match:
            findings.append(
                f"{prefix}: adapter_test anchor must read adapter/opencode/<file>.test.ts#<test name>: {value!r}"
            )
        elif not adapter_test_exists(match.group("file"), match.group("test")):
            findings.append(f"{prefix}: adapter_test anchor does not resolve: {value!r}")
        elif not adapter_suite_runs_in_ci():
            findings.append(f"{prefix}: adapter suite is not run by a required workflow")
    elif kind == "generated":
        match = GENERATED_ANCHOR.fullmatch(value)
        if not match:
            findings.append(f"{prefix}: generated anchor must read <path>#<symbol>: {value!r}")
        elif not generated_symbol_exists(match.group("file"), match.group("symbol")):
            findings.append(f"{prefix}: generated anchor does not resolve to a generated artifact: {value!r}")


def main(argv: list[str] | None = None) -> int:
    """Execute one generated anchor without invoking other proof tools."""
    arguments = sys.argv[1:] if argv is None else argv
    if len(arguments) != 4 or arguments[0] != "--kind" or arguments[2] != "--value":
        print(
            "usage: evidence_anchors.py --kind generated --value <relative-path>#<symbol>",
            file=sys.stderr,
        )
        return 2
    kind, value = arguments[1], arguments[3]
    if kind != "generated":
        print(f"unsupported anchor kind: {kind[:80]!r}; only 'generated' has an executable entry", file=sys.stderr)
        return 2
    findings: list[str] = []
    check_anchor({"kind": kind, "value": value}, "generated-anchor", findings)
    for finding in findings:
        print(finding, file=sys.stderr)
    return 1 if findings else 0


if __name__ == "__main__":
    raise SystemExit(main())
