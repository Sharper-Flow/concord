// These joins describe the selected check, not a successful execution. The
// native receipt owner still owes the exact candidate's observed witnesses.
func projectToolingAnchorCase(anchor FootprintCheck, recipe NativeRecipeCase, read func(string) ([]byte, error), scenarioSources []string, invocation string) error {
	fail := func() error { return fmt.Errorf("unsupported or unrelated typed anchor/selected-case relation") }
	command, inputs, direct := projectToolingDirectCommand(invocation)
	if !direct {
		return fail()
	}
	switch anchor.Kind {
	case "go_test":
		pkg, test, ok := strings.Cut(anchor.Value, ".")
		if !ok || recipe.Kind != "go_top_level_v1" || recipe.Cwd != pkg || !nativeOracleTestName.MatchString(test) || !slices.Contains(recipe.Witnesses, test) {
			return fail()
		}
		return projectToolingGoWitnessSource(recipe, test, read)
	case "go_package":
		pkg := "./" + recipe.Cwd
		if recipe.Kind != nativeGoPackageKind || anchor.Value != pkg || !slices.Equal(recipe.Witnesses, []string{"go_package:" + pkg}) {
			return fail()
		}
	case "scenario":
		return projectToolingScenarioCase(anchor.Value, recipe, read, scenarioSources, command, inputs)
	case "adapter_test":
		file, test, ok := strings.Cut(anchor.Value, "#")
		if !ok || !strings.HasPrefix(file, "adapter/opencode/") || test == "" {
			return fail()
		}
		for _, check := range recipe.checks {
			files, expected, ok := projectToolingAdapterCommand(recipe, check)
			if ok && command == "bun" && slices.Contains(inputs, file) && slices.Contains(files, file) && slices.Contains(expected, test) {
				return nil
			}
		}
		return fail()
	case "validator":
		if command != "python3" || !slices.Equal(inputs, []string{anchor.Value}) || !regexp.MustCompile(`^scripts/(check|test)-[a-z0-9-]+\.py$`).MatchString(anchor.Value) || !projectToolingSelectedPython(recipe, anchor.Value, nil) {
			return fail()
		}
	case "generated":
		return projectToolingGeneratedCase(anchor.Value, recipe, read, command, inputs)
	default:
		return fail()
	}
	return nil
}

func projectToolingScenarioCase(id string, recipe NativeRecipeCase, read func(string) ([]byte, error), scenarioSources []string, command string, inputs []string) error {
	corpus, err := projectToolingScenarioCorpus(id, recipe, read, scenarioSources)
	if err != nil {
		return err
	}
	if recipe.Kind == "go_top_level_v1" {
		for _, witness := range recipe.Witnesses {
			// A parent, a package, and an id-shaped opaque label are not
			// an exact nested Go witness.
			if nativeGoWitnessValid(witness) && strings.HasSuffix(witness, "/"+id) {
				root, _, _ := strings.Cut(witness, "/")
				return projectToolingGoWitnessSource(recipe, root, read)
			}
		}
		return fmt.Errorf("unsupported or unrelated typed anchor/selected-case relation")
	}
	return projectToolingAdapterScenarioCase(id, corpus, recipe, read, command, inputs)
}

func projectToolingAdapterScenarioCase(id, corpus string, recipe NativeRecipeCase, read func(string) ([]byte, error), command string, inputs []string) error {
	for _, check := range recipe.checks {
		files, expected, ok := projectToolingAdapterCommand(recipe, check)
		if !ok || !slices.Contains(expected, id) {
			continue
		}
		owners := 0
		for _, file := range files {
			raw, err := read(file)
			if err != nil {
				return err
			}
			quotedID, _ := json.Marshal(id)
			importPath, _ := json.Marshal("../../" + corpus)
			registration := regexp.MustCompile(`\btest\(\s*` + regexp.QuoteMeta(string(quotedID)) + `\s*,`)
			if command == "bun" && slices.Contains(inputs, file) && strings.Contains(string(raw), string(importPath)) && registration.Match(raw) && strings.Contains(string(raw), "assertScenario("+string(quotedID)+",") {
				owners++
			}
		}
		if owners == 1 {
			return nil
		}
	}
	return fmt.Errorf("unsupported or unrelated typed anchor/selected-case relation")
}

func projectToolingGeneratedCase(value string, recipe NativeRecipeCase, read func(string) ([]byte, error), command string, inputs []string) error {
	fail := func() error { return fmt.Errorf("unsupported or unrelated typed anchor/selected-case relation") }
	file, symbol, ok := strings.Cut(value, "#")
	if !ok || !projectToolingPathValid(file) || !regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`).MatchString(symbol) {
		return fail()
	}
	raw, err := read(file)
	if err != nil {
		return err
	}
	owner := regexp.MustCompile(`(?m)^// Code generated by (scripts/generate-[a-z0-9-]+\.py); DO NOT EDIT\.`).FindSubmatch(raw)
	if len(owner) != 2 || !regexp.MustCompile(`\b`+regexp.QuoteMeta(symbol)+`\b`).Match(raw) {
		return fail()
	}
	generator := string(owner[1])
	parity := "scripts/test-" + strings.TrimPrefix(generator, "scripts/")
	if command != "python3" || !slices.Equal(inputs, []string{parity}) || !projectToolingSelectedPython(recipe, generator, []string{"--check"}) || !projectToolingSelectedPython(recipe, parity, nil) {
		return fail()
	}
	// Resolve the actual owner and its parity consumer, not any script
	// present beside them in the pinned harness inventory.
	generatorRaw, err := read(generator)
	if err != nil {
		return err
	}
	parityRaw, err := read(parity)
	if err != nil {
		return err
	}
	if !strings.Contains(string(generatorRaw), `"`+file+`"`) || !strings.Contains(string(generatorRaw), symbol) || !strings.Contains(string(parityRaw), `"`+generator+`"`) {
		return fail()
	}
	return nil
}

func projectToolingGoWitnessSource(recipe NativeRecipeCase, test string, read func(string) ([]byte, error)) error {
	count := 0
	for _, name := range recipe.HarnessFiles {
		raw, err := read(name)
		if err != nil {
			return err
		}
		file, err := parser.ParseFile(token.NewFileSet(), name, raw, 0)
		if err != nil {
			return err
		}
		aliases := map[string]bool{}
		for _, imp := range file.Imports {
			if imp.Path.Value == `"testing"` {
				alias := "testing"
				if imp.Name != nil {
					alias = imp.Name.Name
				}
				aliases[alias] = true
			}
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if ok && fn.Recv == nil && fn.Name.Name == test {
				if err := validateNativeGoTestSignature(fn, aliases); err != nil {
					return err
				}
				count++
			}
		}
	}
	if count != 1 {
		return fmt.Errorf("selected Go witness must have one pinned source declaration, found %d", count)
	}
	return nil
}

func projectToolingRelativePath(cwd, name string) string {
	if cwd == "." {
		return strings.TrimPrefix(name, "./")
	}
	if !strings.HasPrefix(name, cwd+"/") {
		return ""
	}
	return strings.TrimPrefix(name, cwd+"/")
}

func projectToolingSelectedPython(recipe NativeRecipeCase, script string, flags []string) bool {
	if recipe.Kind != nativeTargetKind || recipe.runner != "check" || !slices.Contains(recipe.HarnessFiles, script) {
		return false
	}
	for _, check := range recipe.checks {
		if slices.Equal(check.Argv, append([]string{"python3", projectToolingRelativePath(recipe.Cwd, script)}, flags...)) {
			return true
		}
	}
	return false
}

// Only the pinned Bun acceptance owner has an admitted exact-name contract.
// Arbitrary target witnesses and generic harness membership do not have one.
func projectToolingAdapterCommand(recipe NativeRecipeCase, check nativeTargetCheck) (files, expected []string, ok bool) {
	args := check.Argv
	if recipe.Kind != nativeTargetKind || recipe.materializer != "bun" || recipe.runner != "check" || recipe.Cwd != "adapter/opencode" || len(args) < 3 || args[0] != "python3" || args[1] != "acceptance.py" || !slices.Contains(recipe.HarnessFiles, "adapter/opencode/acceptance.py") {
		return nil, nil, false
	}
	wantsNames := false
	for _, arg := range args[2:] {
		if arg == "--expect" {
			if wantsNames {
				return nil, nil, false
			}
			wantsNames = true
			continue
		}
		if wantsNames {
			if arg == "" || strings.HasPrefix(arg, "-") || slices.Contains(expected, arg) {
				return nil, nil, false
			}
			expected = append(expected, arg)
		} else {
			name := path.Join(recipe.Cwd, arg)
			if path.Base(arg) != arg || !strings.HasSuffix(arg, ".test.ts") || !slices.Contains(recipe.HarnessFiles, name) || slices.Contains(files, name) {
				return nil, nil, false
			}
			files = append(files, name)
		}
	}
	return files, expected, len(files) > 0 && (!wantsNames || len(expected) > 0)
}

func projectToolingScenarioSources(ctx context.Context, runner GitRunner, repo, commit string) ([]string, error) {
	raw, err := runner.Run(ctx, repo, "ls-tree", "-r", "-z", commit, "--", ".concord/scenarios", "internal")
	if err != nil {
		return nil, err
	}
	if len(raw) > 2*1024*1024 {
		return nil, fmt.Errorf("scenario source inventory exceeds 2097152 bytes")
	}
	entries, err := parseTreeEntries(raw)
	if err != nil {
		return nil, err
	}
	names := []string{}
	for _, entry := range entries {
		if strings.HasPrefix(entry.path, ".concord/scenarios/") && strings.HasSuffix(entry.path, ".json") || strings.HasPrefix(entry.path, "internal/") && strings.HasSuffix(entry.path, "_test.go") {
			names = append(names, entry.path)
		}
	}
	if len(names) > nativeGoInputFileLimit {
		return nil, fmt.Errorf("scenario source inventory exceeds 4096 files")
	}
	return names, nil
}

func projectToolingScenarioCorpus(id string, recipe NativeRecipeCase, read func(string) ([]byte, error), sources []string) (string, error) {
	count, corpus := 0, ""
	for _, file := range sources {
		if !strings.HasPrefix(file, ".concord/scenarios/") || !strings.HasSuffix(file, ".json") {
			continue
		}
		raw, err := read(file)
		if err != nil {
			return "", err
		}
		var document struct {
			Scenarios []json.RawMessage `json:"scenarios"`
		}
		if err := rejectDuplicateJSONKeys(raw); err != nil {
			return "", err
		}
		if err := json.Unmarshal(raw, &document); err != nil {
			return "", err
		}
		matches, err := projectToolingScenarioIDCount(document.Scenarios, id)
		if err != nil {
			return "", err
		}
		count += matches
		if matches > 0 {
			corpus = file
		}
	}
	if count != 1 || !slices.Contains(recipe.FixtureFiles, corpus) {
		return "", fmt.Errorf("scenario must name one exact pinned corpus id, found %d", count)
	}
	if err := projectToolingScenarioNotDeferred(id, uniqueSorted(slices.Concat(sources, recipe.HarnessFiles)), read); err != nil {
		return "", err
	}
	return corpus, nil
}

func projectToolingScenarioIDCount(items []json.RawMessage, id string) (int, error) {
	count := 0
	for _, item := range items {
		var scenario struct {
			ID    string            `json:"id"`
			Cases []json.RawMessage `json:"cases"`
		}
		if err := json.Unmarshal(item, &scenario); err != nil {
			return 0, err
		}
		if scenario.ID == id {
			count++
		}
		nested, err := projectToolingScenarioIDCount(scenario.Cases, id)
		if err != nil {
			return 0, err
		}
		count += nested
	}
	return count, nil
}

func projectToolingScenarioNotDeferred(id string, sources []string, read func(string) ([]byte, error)) error {
	deferral := regexp.MustCompile(`Deferrals\[\s*["']` + regexp.QuoteMeta(id) + `["']\s*\]\s*=`)
	for _, file := range sources {
		if !strings.HasSuffix(file, "_test.go") {
			continue
		}
		raw, err := read(file)
		if err != nil {
			return err
		}
		if deferral.Match(raw) {
			return fmt.Errorf("scenario is deferred")
		}
	}
	return nil
}
