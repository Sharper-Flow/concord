#!/usr/bin/env python3
"""Generate the Go conflict-rule catalog from the checked table.

The generated file is metadata consumed by tests and the conflict recorder:
the pinned priorities.md source hash, the catalog generation, and the closed set of
valid rule IDs and A2 row identifiers. It carries no approval classifier, no
copied policy text, and no second sizing owner; LIVE validation only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "contracts/conflict-rules.v1.json"
OUTPUT = ROOT / "internal/store/generated_conflict_rules.go"
GENERATOR = "scripts/generate-conflict-rules.py"
RULE_ID = re.compile(r"^(?:R[1-9][0-9]*|P[1-9][0-9]*|S|U)$")


def load() -> dict:
    value = json.loads(TABLE.read_text(encoding="utf-8"))
    if value.get("schema_version") != "1.1":
        raise SystemExit(f"{TABLE}: schema_version must be 1.1")
    source = value.get("source")
    if not isinstance(source, dict) or not str(source.get("sha256", "")).startswith("sha256:"):
        raise SystemExit(f"{TABLE}: source.sha256 must pin the checked priorities.md snapshot")
    rules = value.get("rules")
    if not isinstance(rules, list) or not rules:
        raise SystemExit(f"{TABLE}: rules must be a non-empty list")
    for rule in rules:
        rule_id = rule.get("id") if isinstance(rule, dict) else None
        if not isinstance(rule_id, str) or not RULE_ID.fullmatch(rule_id):
            raise SystemExit(f"{TABLE}: rule id {rule_id!r} is not a conflict-rule ID")
    rows = value.get("a2")
    if not isinstance(rows, list) or not rows:
        raise SystemExit(f"{TABLE}: a2 must be a non-empty list")
    for row in rows:
        number = row.get("row") if isinstance(row, dict) else None
        if not isinstance(number, int) or isinstance(number, bool) or number < 1:
            raise SystemExit(f"{TABLE}: a2 row numbers must be positive integers")
    generation = value.get("catalog_generation")
    if not isinstance(generation, int) or isinstance(generation, bool) or generation < 1:
        raise SystemExit(f"{TABLE}: catalog_generation must be a positive per-revision identity")
    return value


def render(value: dict) -> str:
    identifiers = list(dict.fromkeys(str(rule["id"]) for rule in value["rules"]))
    row_ids = sorted(
        list(dict.fromkeys(f"A2-{int(row['row'])}" for row in value["a2"])),
        key=lambda identifier: int(identifier.split("-")[1]),
    )
    lines = [
        "// Code generated by " + GENERATOR + "; DO NOT EDIT.",
        "",
        "package store",
        "",
        "// conflictRuleSourceHash pins the priorities.md snapshot the shipped",
        "// conflict-rule table was checked against (CD-0230 D6). The conflict",
        "// recorder consumes it; it never classifies consent.",
        f"const conflictRuleSourceHash = {json.dumps(str(value['source']['sha256']))}",
        "",
        "// conflictRuleCatalogGeneration is the table's per-revision identity.",
        "// Consumers pin it beside the source hash; it never classifies consent.",
        f"const conflictRuleCatalogGeneration = {int(value['catalog_generation'])}",
        "",
        "// conflictRuleIDSet is the closed set of valid conflict-rule IDs and A2",
        "// row identifiers the checked table carries.",
        "var conflictRuleIDSet = map[string]bool{",
    ]
    # Emit the gofmt-aligned form so --check compares stable bytes.
    catalog = identifiers + row_ids
    width = max(len(identifier) for identifier in catalog)
    for identifier in catalog:
        entry = f'"{identifier}":'
        lines.append(f"\t{entry}{' ' * (width - len(identifier) + 1)}true,")
    lines += [
        "}",
        "",
        "// validConflictRuleID reports whether value names a checked conflict-rule",
        "// ID or A2 row identifier. LIVE validation only: it never approves a",
        "// conflict application or classifies an approval point.",
        "func validConflictRuleID(value string) bool {",
        "\treturn conflictRuleIDSet[value]",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the generated file drifts")
    arguments = parser.parse_args()
    rendered = render(load())
    if arguments.check:
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            print(f"{OUTPUT} drifts from {TABLE}; rerun {GENERATOR}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
