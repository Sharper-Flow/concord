#!/usr/bin/env python3
"""Shared typed-anchor machinery for evidence-binding validators.

The floor-readiness and law-coverage validators both judge whether a `satisfied`
record is proved rather than asserted. The proof layer is the same in both
planes: typed anchors must resolve, and the executable kinds must be invoked
by a required workflow. Without a single source of truth the two validators
would drift and a record that one validator accepted would be a finding to the
other — the same defect restated in two syntaxes (CD-0047 D3).

Document-contract citations reuse native Go declaration presence without
claiming the stronger coverage assertion verdict.

What an anchor is:
- `go_test`: a Go test identified as `<package>.<TestName>`; resolves when the
  test is declared in that package and its body, or a same-package helper it
  calls, reaches a testing failure call. `go test ./...` is a required CI step.
- `scenario`: a unique direct corpus entry under `.concord/scenarios/` that
  nothing in `internal/` defers. Continuity entries also require an executable
  consuming-test binding in tooling. This is structural reachability only;
  native results and Review establish execution and assertion adequacy.
- `validator`: a Python checker or harness identified by `scripts/<prefix>-<name>.py`;
  resolves when the script exists and either the required CI workflow invokes
  it directly, or `scripts/check-json.py` nests it. A checker that exists but
  is wired into nothing proves nothing, which is the failure mode this whole
  machinery exists to surface.
- `generated`: a symbol owned by a generated artifact, identified as
  `<path>#<symbol>`; resolves when the symbol appears in a file whose leading
  comment carries the generator marker. Hand-written files carry no such
  guarantee.

The validator anchor pattern widens here to `scripts/(check|test)-*.py` so the
release/install test scripts are legal anchors too. The CI-invocation proof is
unchanged in principle: the script must appear in a required workflow file
(`.github/workflows/ci.yml`, `.github/workflows/release.yml`, or
`.github/workflows/pr-linear-link.yml`) or be nested via
`scripts/check-json.py`.
"""
