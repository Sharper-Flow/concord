#!/usr/bin/env python3
"""Validate that every recorded law declares how it is proved.

scripts/check-knowledge-index.py proves record integrity: that the manifest
describes real, unmodified documents, and that no CD file escapes the index.
That is a different proposition from whether any of those documents is
implemented. Its own comment says it fires "before the recorded law and the
current implementation drift apart silently"; the check below that comment is
`target.is_file()`.

This validator owns the missing proposition. Every record in the knowledge
index carries a coverage state, and a `satisfied` state cites typed anchors
that resolve and — where the anchor is executable — that a required check
actually runs. A repository path is not an anchor: paths are exactly what the
existing drift audit accepts, and accepting them here would restate the defect
in new syntax (CD-0047 D3).

The subject set comes from the knowledge index rather than from this manifest,
so a record cannot escape coverage by being absent (CD-0047 D1).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from coverage_state import (  # noqa: E402
    MAX_EVIDENCE,
    STATES,
    bounded_text,
    check_state_obligations,
    check_subject_set,
    load_json,
    report,
)

MANIFEST = ROOT / "docs/law-coverage.v1.json"
SCHEMA = ROOT / "contracts/law-coverage.schema.json"
INDEX = ROOT / "docs/concord-knowledge-index.v1.json"
WORKFLOW = ROOT / ".github/workflows/ci.yml"

ALLOWED_ROOT = {"schema_version", "source", "records"}
ALLOWED_RECORD = {"id", "state", "evidence", "issue", "reason"}
ANCHOR_KINDS = ("go_test", "scenario", "validator", "generated")

GO_TEST_ANCHOR = re.compile(r"^(?P<package>[a-z0-9/_]+)\.(?P<test>Test[A-Za-z0-9_]*)$")
VALIDATOR_ANCHOR = re.compile(r"^scripts/check-[a-z0-9-]+\.py$")
GENERATED_ANCHOR = re.compile(r"^(?P<file>[A-Za-z0-9./_-]+)#(?P<symbol>[A-Za-z_][A-Za-z0-9_]*)$")

GENERATED_MARKER = "Code generated by"


def go_test_exists(package: str, test: str) -> bool:
    """A Go test anchor resolves when the named test is declared in that package.

    `go test ./...` is a required CI step and covers every package in the
    module, so package membership is the whole of the executability question
    for this kind — there is no per-package opt-in that could exclude it.
    """
    directory = ROOT / package
    if not directory.is_dir():
        return False
    declaration = re.compile(rf"^func {re.escape(test)}\(", re.MULTILINE)
    return any(
        declaration.search(path.read_text(encoding="utf-8", errors="replace"))
        for path in directory.glob("*_test.go")
    )


DEFERRAL = re.compile(r"""Deferrals\[\s*["'](?P<id>[^"']+)["']\s*\]\s*=""")


def deferred_scenarios() -> set[str]:
    """Scenario ids the corpus harnesses record as deferred rather than bound.

    A deferred scenario sits in the corpus and is executed by nothing. Accepting
    one as evidence would assert a rule that no test enforces — presence
    standing in for enforcement, which is the exact defect this manifest
    exists to surface. Reading the same registry the corpus test reads keeps
    the two answers from diverging.
    """
    found: set[str] = set()
    for path in (ROOT / "internal").rglob("*_test.go"):
        for match in DEFERRAL.finditer(path.read_text(encoding="utf-8", errors="replace")):
            found.add(match.group("id"))
    return found


def scenario_exists(scenario_id: str) -> bool:
    """A scenario anchor resolves when a corpus declares the id and nothing defers it."""
    if scenario_id in deferred_scenarios():
        return False
    directory = ROOT / "scenarios"
    if not directory.is_dir():
        return False
    for path in directory.rglob("*.json"):
        try:
            corpus = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            continue
        if scenario_id in collect_ids(corpus):
            return True
    return False


def collect_ids(value: object) -> set[str]:
    found: set[str] = set()
    if isinstance(value, dict):
        for key, item in value.items():
            if key in {"id", "scenario_id", "scenario"} and isinstance(item, str):
                found.add(item)
            found |= collect_ids(item)
    elif isinstance(value, list):
        for item in value:
            found |= collect_ids(item)
    return found


def validator_runs_in_ci(script: str) -> bool:
    """A validator anchor resolves when CI actually invokes the script.

    A checker that exists but is not wired into the required workflow proves
    nothing, which is the failure mode this whole manifest exists to surface.
    check-json.py nests several sub-validators, so a nested invocation counts.
    """
    if not (ROOT / script).is_file():
        return False
    if not WORKFLOW.is_file():
        return False
    if script in WORKFLOW.read_text(encoding="utf-8"):
        return True
    nested = ROOT / "scripts/check-json.py"
    return nested.is_file() and script in nested.read_text(encoding="utf-8")


def generated_symbol_exists(file: str, symbol: str) -> bool:
    """A generated anchor resolves when the symbol lives in a generated artifact.

    The artifact must carry the generator marker, because the guarantee being
    cited is that a generator owns the value — a hand-written file with the
    right symbol name carries no such guarantee.
    """
    target = ROOT / file
    if not target.is_file():
        return False
    text = target.read_text(encoding="utf-8", errors="replace")
    if GENERATED_MARKER not in text:
        return False
    return re.search(rf"\b{re.escape(symbol)}\b", text) is not None


def check_anchor(anchor: object, prefix: str, findings: list[str]) -> None:
    if not isinstance(anchor, dict):
        findings.append(f"{prefix}: anchor must be an object")
        return
    if set(anchor) != {"kind", "value"}:
        findings.append(f"{prefix}: anchor must carry exactly kind and value")
        return
    kind, value = anchor["kind"], anchor["value"]
    if kind not in ANCHOR_KINDS:
        findings.append(f"{prefix}: anchor kind must be one of {list(ANCHOR_KINDS)}, got {kind!r}")
        return
    if not bounded_text(value, 3, 512):
        findings.append(f"{prefix}: anchor value must be trimmed text of 3-512 characters")
        return

    if kind == "go_test":
        match = GO_TEST_ANCHOR.fullmatch(value)
        if not match:
            findings.append(f"{prefix}: go_test anchor must read <package>.<TestName>: {value!r}")
        elif not go_test_exists(match.group("package"), match.group("test")):
            findings.append(f"{prefix}: go_test anchor does not resolve: {value!r}")
    elif kind == "scenario":
        if not scenario_exists(value):
            findings.append(f"{prefix}: scenario anchor is in no corpus under scenarios/: {value!r}")
    elif kind == "validator":
        if not VALIDATOR_ANCHOR.fullmatch(value):
            findings.append(f"{prefix}: validator anchor must read scripts/check-<name>.py: {value!r}")
        elif not validator_runs_in_ci(value):
            findings.append(f"{prefix}: validator anchor is not invoked by CI: {value!r}")
    elif kind == "generated":
        match = GENERATED_ANCHOR.fullmatch(value)
        if not match:
            findings.append(f"{prefix}: generated anchor must read <path>#<symbol>: {value!r}")
        elif not generated_symbol_exists(match.group("file"), match.group("symbol")):
            findings.append(f"{prefix}: generated anchor does not resolve to a generated artifact: {value!r}")


def indexed_record_ids(findings: list[str]) -> list[str]:
    index = load_json(INDEX, findings)
    if not isinstance(index, dict):
        findings.append("knowledge index is not an object")
        return []
    records = index.get("records")
    if not isinstance(records, list):
        findings.append("knowledge index has no records array")
        return []
    ids: list[str] = []
    for record in records:
        if isinstance(record, dict) and isinstance(record.get("id"), str):
            ids.append(record["id"])
    return ids


def check_schema_states() -> list[str]:
    """The published schema must enumerate the shared vocabulary, not a copy of it."""
    findings: list[str] = []
    document = load_json(SCHEMA, findings)
    if not isinstance(document, dict):
        return findings
    enum = (
        document.get("properties", {})
        .get("records", {})
        .get("items", {})
        .get("properties", {})
        .get("state", {})
        .get("enum")
    )
    if enum != list(STATES):
        findings.append(
            f"{SCHEMA.name}: state enum must equal the shared vocabulary {list(STATES)}, got {enum!r}"
        )
    return findings


def main() -> int:
    findings: list[str] = check_schema_states()
    manifest = load_json(MANIFEST, findings)
    if not isinstance(manifest, dict):
        return report(findings, "law coverage")

    unknown = set(manifest) - ALLOWED_ROOT
    if unknown:
        findings.append(f"unknown manifest keys: {sorted(unknown)}")
    if manifest.get("schema_version") != "1.0":
        findings.append("schema_version must be \"1.0\"")

    records = manifest.get("records")
    if not isinstance(records, list) or not records:
        findings.append("records must be a non-empty array")
        return report(findings, "law coverage")

    declared: list[str] = []
    for record in records:
        if not isinstance(record, dict):
            findings.append("record must be an object")
            continue
        identifier = record.get("id")
        if not bounded_text(identifier, 2, 128):
            findings.append(f"record id must be trimmed text: {identifier!r}")
            continue
        declared.append(identifier)
        prefix = f"record {identifier}"

        unknown_fields = set(record) - ALLOWED_RECORD
        if unknown_fields:
            findings.append(f"{prefix}: unknown fields: {sorted(unknown_fields)}")

        if not check_state_obligations(record, prefix, findings):
            continue

        if record.get("state") == "satisfied":
            evidence = record.get("evidence")
            if not isinstance(evidence, list) or not evidence:
                findings.append(f"{prefix}: evidence must be a non-empty array of anchors")
            elif len(evidence) > MAX_EVIDENCE:
                findings.append(f"{prefix}: evidence must carry at most {MAX_EVIDENCE} anchors")
            else:
                for position, anchor in enumerate(evidence):
                    check_anchor(anchor, f"{prefix} anchor {position}", findings)

    check_subject_set(declared, indexed_record_ids(findings), "law record", findings)
    return report(findings, "law coverage")


if __name__ == "__main__":
    raise SystemExit(main())
