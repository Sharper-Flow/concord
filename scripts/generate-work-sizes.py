#!/usr/bin/env python3
"""Validate and deterministically generate work-size projections."""
from __future__ import annotations

import json
from pathlib import Path

from vocabulary_utils import fail, generate_projections, gofmt


ROOT = Path(__file__).resolve().parents[1]
VOCABULARY = ROOT / "contracts/work-sizes.v1.json"
SCHEMA = ROOT / "contracts/work-sizes.schema.json"


def go_name(size: str) -> str:
    return "WorkSize" + "".join(part.capitalize() for part in size.split("_"))


def go_projection(vocabulary: dict) -> str:
    constants = "\n".join(
        f"\t// {item['summary']}\n\t{go_name(item['size'])} WorkSize = {json.dumps(item['size'])}"
        for item in vocabulary["sizes"]
    )
    return f'''// Code generated by scripts/generate-work-sizes.py; DO NOT EDIT.
package store

// WorkSize is one value of the closed size vocabulary declared in
// contracts/work-sizes.v1.json, listed from least to most ceremony.
type WorkSize string

const (
{constants}
)
'''


def semantic(vocabulary: dict) -> None:
    names = [item["size"] for item in vocabulary["sizes"]]
    if len(set(names)) != len(names):
        fail("work sizes must be unique")


def project(vocabulary: dict, vocabulary_digest: str) -> dict[Path, str]:
    return {
        ROOT / "internal/store/generated_work_sizes.go": gofmt(go_projection(vocabulary)),
        ROOT / "contracts/work-sizes.digest": vocabulary_digest + "\n",
    }


def main() -> int:
    return generate_projections("work-size", VOCABULARY, SCHEMA, ROOT, project, semantic)


if __name__ == "__main__":
    raise SystemExit(main())
